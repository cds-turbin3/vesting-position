use std::fs;
use std::path::Path;

/// One report's row in the index: the test's title, its report slug, and the
/// source span the report's permalink points at.
struct Row {
    title: String,
    slug: String,
    file: String,
    line: u32,
}

/// Render `test-report/index.md`: a table of every report, sorted by title, each
/// row linking to the report and (when `source_base` is set) to a pinned source
/// permalink built the same way the reports' own `**Source:**` links are.
fn render_index(rows: &mut [Row], source_base: Option<&str>) -> String {
    rows.sort_by(|a, b| a.title.cmp(&b.title));
    let mut out = String::from(
        "# Test reports\n\nGenerated by `make test-report`.\n\n| Test | Report | Source |\n|---|---|---|\n",
    );
    for r in rows.iter() {
        let source = match source_base {
            Some(base) if !base.is_empty() => {
                format!("[`{f}` L{l}]({base}{f}#L{l})", f = r.file, l = r.line)
            }
            _ => format!("`{f}` L{l}", f = r.file, l = r.line),
        };
        out.push_str(&format!(
            "| {} | [report]({}.md) | {} |\n",
            r.title, r.slug, source
        ));
    }
    out
}

/// Insert `// Report: test-report/<slug>.md` immediately above the `#[test]`
/// attribute (or the `fn` line if no attribute) of the test enclosing 1-based
/// `line`. Idempotent: an existing `// Report:` line there is replaced. Returns
/// `None` when `line` is not inside a test fn (nothing edited).
fn inject(src: &str, line: u32, slug: &str) -> Option<String> {
    let lines: Vec<&str> = src.lines().collect();
    let idx = (line as usize).checked_sub(1)?;
    if idx >= lines.len() {
        return None;
    }
    // Scan up to the `fn` line of the enclosing item.
    let mut fn_idx = idx;
    while !lines[fn_idx].trim_start().starts_with("fn ") && !lines[fn_idx].contains(" fn ") {
        if fn_idx == 0 {
            return None;
        }
        fn_idx -= 1;
    }
    // Then up past attributes (`#[...]`) to the insertion point.
    let mut at = fn_idx;
    while at > 0 && lines[at - 1].trim_start().starts_with('#') {
        at -= 1;
    }
    let comment = format!("// Report: test-report/{slug}.md");
    let mut out: Vec<String> = lines.iter().map(|l| l.to_string()).collect();
    // Idempotence: replace an existing back-link directly above `at`.
    if at > 0 && out[at - 1].trim_start().starts_with("// Report:") {
        out[at - 1] = comment;
    } else {
        out.insert(at, comment);
    }
    let mut joined = out.join("\n");
    if src.ends_with('\n') {
        joined.push('\n');
    }
    Some(joined)
}

fn main() {
    let manifest = env!("CARGO_MANIFEST_DIR");
    let floors = Path::new(manifest).join("test-report/.floors");
    let entries = match fs::read_dir(&floors) {
        Ok(e) => e,
        Err(_) => {
            eprintln!("no floors at {}; run `make test-report` first", floors.display());
            std::process::exit(1);
        }
    };
    let mut rows: Vec<Row> = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let json: serde_json::Value =
            serde_json::from_str(&fs::read_to_string(&path).unwrap()).unwrap();
        let slug = json["slug"].as_str().unwrap();
        let prov = &json["provenance"];
        if prov.is_null() {
            eprintln!("floor {slug} has no provenance; skipping");
            continue;
        }
        let file = prov["file"].as_str().unwrap();
        let line = prov["line"].as_u64().unwrap() as u32;
        let title = json["title"].as_str().unwrap_or(slug);
        rows.push(Row {
            title: title.to_string(),
            slug: slug.to_string(),
            file: file.to_string(),
            line,
        });
        let src_path = Path::new(manifest).join(file);
        let src = fs::read_to_string(&src_path).unwrap();
        match inject(&src, line, slug) {
            Some(updated) => {
                fs::write(&src_path, updated).unwrap();
                println!("linked {file} -> test-report/{slug}.md");
            }
            None => eprintln!("could not locate a test fn at {file}:{line}; skipping {slug}"),
        }
    }

    let source_base = std::env::var("FROOD_SOURCE_BASE").ok();
    let index = render_index(&mut rows, source_base.as_deref());
    fs::write(Path::new(manifest).join("test-report/index.md"), index).unwrap();
    println!("wrote test-report/index.md ({} reports)", rows.len());
}

#[cfg(test)]
mod tests {
    use super::inject;
    use super::{render_index, Row};

    const SRC: &str = "\
use frood::Story;

#[test]
fn vested_tokens_are_forfeited() {
    let x = 1;
}
";

    #[test]
    fn inserts_backlink_above_the_test_attr() {
        // line 6 (1-based) is `let x = 1;`, inside the fn.
        let out = inject(SRC, 6, "vested-tokens-forfeited").unwrap();
        assert!(out.contains("// Report: test-report/vested-tokens-forfeited.md\n#[test]"), "{out}");
    }

    #[test]
    fn is_idempotent() {
        let once = inject(SRC, 6, "vested-tokens-forfeited").unwrap();
        let twice = inject(&once, 7, "vested-tokens-forfeited").unwrap();
        assert_eq!(once, twice, "second run must not duplicate the back-link");
    }

    #[test]
    fn skips_span_outside_any_test() {
        // line 2 is the `use` line, no enclosing #[test].
        assert!(inject(SRC, 2, "x").is_none());
    }

    #[test]
    fn index_renders_report_and_source_links() {
        let mut rows = vec![Row {
            title: "Vested tokens forfeited".into(),
            slug: "vested-tokens-forfeited".into(),
            file: "tests/forfeiture.rs".into(),
            line: 122,
        }];
        let base = "https://github.com/o/r/blob/deadbeef/babelfish-tests/";
        let md = render_index(&mut rows, Some(base));
        assert!(
            md.contains("| Vested tokens forfeited | [report](vested-tokens-forfeited.md) |"),
            "{md}"
        );
        assert!(
            md.contains("(https://github.com/o/r/blob/deadbeef/babelfish-tests/tests/forfeiture.rs#L122)"),
            "{md}"
        );
    }
}
